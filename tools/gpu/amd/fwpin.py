#!/usr/bin/env python3
"""Generate the Polaris firmware digest pin header from the vendored MANIFEST.

Usage: fwpin.py third_party/amd-firmware/MANIFEST build/gen/polaris_fw_pin.h

WHY A GENERATED HEADER. The kernel accepts a firmware blob only if its SHA-256
equals the digest recorded here (c/drivers/gpu/amd/polaris/resource/files.c),
whichever way the blob arrived: from /lib/firmware/amdgpu on the root disk or
from a boot module on the ESP. The pin must therefore come from the same file
that records which linux-firmware commit the blobs were taken from, not from a
second hand-copied table that could drift from it. MANIFEST lines of the form
"  <64 hex digits>  <name>" are the only input; everything else is prose.

A MANIFEST without a single pin, a malformed digest or a repeated name is a
refusal, because an empty or ambiguous table would make the kernel reject
every file (or, worse, a hand-edited duplicate could pin an old digest).
"""
import re
import sys

PIN_LINE = re.compile(r"^\s+([0-9a-f]{64})\s+(\S+)\s*$")
COMMIT_LINE = re.compile(r"^commit:\s+([0-9a-f]{40})\s*$")


def die(message):
    sys.exit(f"fwpin: {message}")


def parse_manifest(path):
    """Return (commit, [(name, digest_hex), ...]) in MANIFEST order."""
    commit = None
    pins = []
    seen = set()
    with open(path, encoding="ascii") as manifest:
        for line in manifest:
            found = COMMIT_LINE.match(line)
            if found:
                commit = found.group(1)
                continue
            found = PIN_LINE.match(line)
            if not found:
                continue
            digest, name = found.groups()
            if name in seen:
                die(f"{path}: {name} is pinned twice")
            seen.add(name)
            pins.append((name, digest))
    if commit is None:
        die(f"{path}: no 'commit:' line")
    if not pins:
        die(f"{path}: no '<sha256>  <name>' lines")
    return commit, pins


def render(commit, pins):
    """C source for the table; digests are written as bytes so the kernel
    compares raw sha256() output without any hex parsing at boot."""
    out = [
        "/* Generated by tools/gpu/amd/fwpin.py from third_party/amd-firmware/MANIFEST.",
        " * Do not edit: change MANIFEST and rebuild. */",
        f'#define POLARIS_FW_PIN_COMMIT "{commit}"',
        "static const struct polaris_fw_pin polaris_fw_pin_generated[] = {",
    ]
    for name, digest in pins:
        octets = ", ".join(f"0x{digest[i:i + 2]}" for i in range(0, 64, 2))
        out.append(f'    {{"{name}", {{{octets}}}}},')
    out.append("};")
    out.append(f"#define POLARIS_FW_PIN_GENERATED_COUNT {len(pins)}u")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 3:
        die("usage: fwpin.py MANIFEST OUT.h")
    commit, pins = parse_manifest(sys.argv[1])
    with open(sys.argv[2], "w", encoding="ascii") as header:
        header.write(render(commit, pins))


if __name__ == "__main__":
    main()
