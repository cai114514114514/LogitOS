#!/usr/bin/env python3
"""Rasterize printable ASCII from fsroot/fonts/mono.ttf into the 8x16 bitmap
font the kernel uses when it has no root filesystem to load fonts from
(c/kernel/diag/hwscreen.c). Output: c/kernel/diag/hwscreen_font.h.

mono.ttf is Logit Mono Regular, a subset of Noto Sans Mono under the SIL Open
Font License 1.1 (fsroot/fonts/README.md, third_party/fonts/); the bitmap is
modified font software under the same license, not under the kernel's own license.
The generated header carries the copyright notice and the complete OFL text as
a string the kernel keeps (OFL condition 2), so kernel.elf, the ISO and the ESP
carry them too.
usage: python3 tools/mkbitmapfont.py [--check]"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'c/kernel/diag/hwscreen_font.h'
W, H, SIZE, BASE = 8, 16, 13, 12

font = ImageFont.truetype(str(ROOT / 'fsroot/fonts/mono.ttf'), SIZE)
rows = []
for code in range(32, 127):
    img = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = '1'                                     # no anti-aliasing: a 1-bit cell
    d.text((0, BASE), chr(code), fill=255, font=font, anchor='ls')
    bits = []
    for y in range(H):
        v = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 128: v |= 0x80 >> x
        bits.append(v)
    rows.append('    { ' + ', '.join('0x%02x' % b for b in bits) + ' },  /* %r */' % chr(code))
ofl = (ROOT / 'third_party/fonts/OFL-NotoSansMono.txt').read_text()
cstr = ''.join('    "%s\\n"\n' % l.replace('\\', '\\\\').replace('"', '\\"') for l in ofl.splitlines())
text = ('/* GENERATED by tools/mkbitmapfont.py from fsroot/fonts/mono.ttf (Noto Sans Mono,\n'
        ' * SIL Open Font License 1.1). Do not edit; rerun the tool. Glyph = 16 rows of\n'
        ' * 8 pixels, MSB leftmost, for codepoints 0x20..0x7e. */\n'
        '#ifndef HWSCREEN_FONT_TABLE_H\n#define HWSCREEN_FONT_TABLE_H\n#include <stdint.h>\n'
        '#define HWSCREEN_FONT_W %d\n#define HWSCREEN_FONT_H %d\n'
        'static const uint8_t hwscreen_font[95][%d] = {\n%s\n};\n'
        '/* The font is a modified version of Noto Sans Mono: its copyright notice and\n'
        ' * licence travel with every binary that contains it (OFL condition 2). */\n'
        '__attribute__((used)) static const char hwscreen_font_notice[] =\n'
        '    "hwscreen bitmap font: modified from Noto Sans Mono (Logit Mono subset)\\n"\n%s;\n'
        '#endif\n') % (W, H, H, '\n'.join(rows), cstr)
if '--check' in sys.argv:
    sys.exit(0 if OUT.read_text() == text else 'hwscreen_font.h is stale: rerun tools/mkbitmapfont.py')
OUT.write_text(text)
print('wrote', OUT)
