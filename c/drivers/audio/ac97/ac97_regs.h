#ifndef LOGIT_AC97_REGS_H
#define LOGIT_AC97_REGS_H

/* Intel ICH native bus-master BAR byte offsets. SiS/ALI have different
 * layouts and must never be admitted by a class-only PCI match. */
enum {
    AC97_INPUT = 0x00, AC97_OUTPUT = 0x10, AC97_MIC = 0x20,
    AC97_DESCRIPTOR_BASE = 0x00, AC97_CURRENT_INDEX = 0x04,
    AC97_LAST_INDEX = 0x05, AC97_STATUS = 0x06,
    AC97_REMAINING_SAMPLES = 0x08, AC97_CONTROL = 0x0b,
    AC97_GLOBAL_CONTROL = 0x2c, AC97_GLOBAL_STATUS = 0x30,
    AC97_CODEC_SEMAPHORE = 0x34,
    AC97_HALTED = 0x01, AC97_CURRENT_LAST = 0x02,
    AC97_LAST_COMPLETE = 0x04, AC97_PERIOD_COMPLETE = 0x08,
    AC97_FIFO_ERROR = 0x10, AC97_STATUS_ACK = 0x1c,
    AC97_RUN = 0x01, AC97_RESET_REGISTERS = 0x02,
    AC97_LAST_IRQ = 0x04, AC97_FIFO_IRQ = 0x08, AC97_PERIOD_IRQ = 0x10,
    AC97_COLD_RELEASE = 0x02, AC97_WARM_RESET = 0x04,
    AC97_LINK_OFF = 0x08,
    AC97_OUTPUT_IRQ = 0x40, AC97_PRIMARY_READY = 0x100,
    AC97_CODEC_READ_TIMEOUT = 0x8000,
    AC97_CODEC_RESET = 0x00, AC97_MASTER_VOLUME = 0x02,
    AC97_MIC_VOLUME = 0x0e, AC97_PCM_VOLUME = 0x18,
    AC97_RECORD_SELECT = 0x1a, AC97_RECORD_GAIN = 0x1c, AC97_POWER = 0x26,
    AC97_RECORD_MICROPHONE = 0x0000, AC97_RECORD_GAIN_12DB = 0x0808,
    AC97_VOLUME_MUTE = 0x8000, AC97_ADC_READY = 0x01,
    AC97_ADC_RATE = 0x32,
    AC97_EXTENDED_ID = 0x28, AC97_EXTENDED_STATUS = 0x2a,
    AC97_DAC_RATE = 0x2c, AC97_VENDOR_HIGH = 0x7c,
    AC97_VENDOR_LOW = 0x7e, AC97_ANALOG_READY = 0x0e,
    AC97_VARIABLE_RATE = 0x01,
    AC97_DESCRIPTOR_COUNT = 32, AC97_RING_PERIODS = 8,
    AC97_PERIOD_BYTES = 4096, AC97_FRAME_BYTES = 4,
    AC97_RATE = 48000,
    AC97_POLL_ATTEMPTS = 1000, AC97_POLL_DELAY_US = 100
};
#define AC97_DESCRIPTOR_IRQ UINT32_C(0x80000000)
#define AC97_RING_BYTES (AC97_RING_PERIODS * AC97_PERIOD_BYTES)
#define AC97_PERIOD_FRAMES (AC97_PERIOD_BYTES / AC97_FRAME_BYTES)

#endif
