/* Transform backpressure is a promise bridge between the readable demand and
 * the writable sink. Enqueueing a full readable queue blocks subsequent writes;
 * a pull releases that gate. Closing, cancellation and error must release both
 * gates, or a pipeline remains pending forever with no callback left to wake it.
 *
 * Text streams capture the already-installed encoding classes through a private
 * installer. A high surrogate at a string chunk boundary is retained until the
 * next chunk; encoding each chunk independently would corrupt a valid pair.
 * This implementation batch awaits the owner's combined verification phase. */
#include "js/streams/transform.h"

static const char SOURCE[] =
"(function (shared, readable, writable) {\n"
"'use strict';\n"
"const G = globalThis, states = new WeakMap(), controllers = new WeakMap();\n"
"const StringType = String;\n"
"const textBrands = new WeakSet();\n"
"const then = shared.then, resolve = shared.resolve, deferred = shared.deferred;\n"
"const operation = shared.operation, accessor = shared.accessor;\n"
"function stateOf(stream) {\n"
"  const state = states.get(stream);\n"
"  if (!state) throw new TypeError('Expected a TransformStream');\n"
"  return state;\n"
"}\n"
"function controllerOf(controller) {\n"
"  const state = controllers.get(controller);\n"
"  if (!state) throw new TypeError('Expected a TransformStreamDefaultController');\n"
"  return state;\n"
"}\n"
"function pressure(state, value) {\n"
"  if (state.backpressure === value) return;\n"
"  state.backpressure = value;\n"
"  if (value) {\n"
"    state.writeGate = deferred();\n"
"    if (state.pullGate) { state.pullGate.resolve(undefined); state.pullGate = null; }\n"
"  } else {\n"
"    state.writeGate.resolve(undefined);\n"
"  }\n"
"}\n"
"function fail(state, reason, keepReadable) {\n"
"  if (state.failed) return;\n"
"  state.failed = true; state.error = reason;\n"
"  if (!keepReadable) readable.error(readable.state(state.readable), reason);\n"
"  writable.error(writable.state(state.writable), reason);\n"
"  pressure(state, false);\n"
"  if (state.pullGate) { state.pullGate.resolve(undefined); state.pullGate = null; }\n"
"}\n"
"function enqueue(state, chunk) {\n"
"  if (state.failed) throw state.error;\n"
"  const source = readable.state(state.readable);\n"
"  try { readable.enqueue(source, chunk); }\n"
"  catch (reason) { fail(state, reason, false); throw reason; }\n"
"  if (!source.reader || !source.reader.requests.length) {\n"
"    if (readable.desiredSize(source) <= 0) pressure(state, true);\n"
"  }\n"
"}\n"
"function TransformStream(transformer, writableStrategy, readableStrategy) {\n"
"  if (!new.target) throw new TypeError(\"TransformStream requires 'new'\");\n"
"  transformer = transformer === undefined ? {} : transformer;\n"
"  if (transformer === null || (typeof transformer !== 'object' && typeof transformer !== 'function'))\n"
"    throw new TypeError('Transformer must be an object');\n"
"  if (transformer.readableType !== undefined || transformer.writableType !== undefined)\n"
"    throw new RangeError('Typed transform streams are not implemented');\n"
"  const state = { readable: null, writable: null, failed: false, error: undefined,\n"
"    backpressure: true, writeGate: deferred(), pullGate: null };\n"
"  const start = deferred();\n"
"  shared.handled(start.promise);\n"
"  const transform = shared.method(transformer, 'transform');\n"
"  const flush = shared.method(transformer, 'flush');\n"
"  const begin = shared.method(transformer, 'start');\n"
"  state.controller = Object.create(TransformStreamDefaultController.prototype);\n"
"  controllers.set(state.controller, state); states.set(this, state);\n"
"  const readStrategy = shared.strategy(readableStrategy, 0);\n"
"  state.readable = new readable.constructor({\n"
"    start: function () { return start.promise; },\n"
"    pull: function () {\n"
"      if (state.failed) return;\n"
"      if (!state.pullGate) state.pullGate = deferred();\n"
"      pressure(state, false);\n"
"      return state.pullGate.promise;\n"
"    },\n"
"    cancel: function (reason) { fail(state, reason, false); }\n"
"  }, readStrategy);\n"
"  state.writable = new writable.constructor({\n"
"    start: function () { return start.promise; },\n"
"    write: function (chunk) {\n"
"      const gate = state.backpressure ? state.writeGate.promise : resolve(undefined);\n"
"      return then(gate, function () {\n"
/* Abort may start erroring while this in-flight write waits for demand. Abort
 * itself still waits for that write (do not invent an eager gate release); once
 * a reader releases backpressure, §6.4.3 must reject the stored writable error
 * BEFORE calling transform. The former failed flag alone delivered a chunk
 * after abort; the public fixture observed that write erroneously fulfill. */
"        const output = writable.state(state.writable);\n"
"        if (output.state === 'erroring' || output.state === 'errored') throw output.error;\n"
"        if (state.failed) throw state.error;\n"
"        let result;\n"
"        try { result = transform ? shared.call(transform, transformer, [chunk, state.controller]) : enqueue(state, chunk); }\n"
"        catch (reason) { fail(state, reason, false); throw reason; }\n"
"        return then(resolve(result), function () {}, function (reason) {\n"
"          fail(state, reason, false); throw reason;\n"
"        });\n"
"      });\n"
"    },\n"
"    close: function () {\n"
"      return then(shared.invoke(flush, transformer, [state.controller]), function () {\n"
"        if (state.failed) throw state.error;\n"
"        readable.close(readable.state(state.readable));\n"
"        if (state.pullGate) { state.pullGate.resolve(undefined); state.pullGate = null; }\n"
"      }, function (reason) { fail(state, reason, false); throw reason; });\n"
"    },\n"
"    abort: function (reason) { fail(state, reason, false); }\n"
"  }, writableStrategy);\n"
"  let result;\n"
"  try { result = begin ? shared.call(begin, transformer, [state.controller]) : undefined; }\n"
"  catch (reason) { start.reject(reason); fail(state, reason, false); throw reason; }\n"
"  then(resolve(result), start.resolve, function (reason) { start.reject(reason); fail(state, reason, false); });\n"
"}\n"
"function TransformStreamDefaultController() { throw new TypeError('Illegal constructor'); }\n"
"accessor(TransformStreamDefaultController.prototype, 'desiredSize', function () {\n"
"  return readable.desiredSize(readable.state(controllerOf(this).readable));\n"
"});\n"
"operation(TransformStreamDefaultController.prototype, 'enqueue', function (chunk) { enqueue(controllerOf(this), chunk); }, 0);\n"
"operation(TransformStreamDefaultController.prototype, 'error', function (reason) { fail(controllerOf(this), reason, false); }, 0);\n"
"operation(TransformStreamDefaultController.prototype, 'terminate', function () {\n"
"  const state = controllerOf(this);\n"
"  const source = readable.state(state.readable);\n"
"  if (source.state === 'readable' && !source.closeRequested) readable.close(source);\n"
"  fail(state, new TypeError('TransformStream was terminated'), true);\n"
"});\n"
"accessor(TransformStream.prototype, 'readable', function () { return stateOf(this).readable; });\n"
"accessor(TransformStream.prototype, 'writable', function () { return stateOf(this).writable; });\n"
"shared.publish('TransformStream', TransformStream, 0);\n"
"shared.publish('TransformStreamDefaultController', TransformStreamDefaultController, 0);\n"
"function installText(Encoder, Decoder) {\n"
"  const encoders = new WeakMap(), decoders = new WeakMap();\n"
"  function textOf(map, value) {\n"
"    const state = map.get(value);\n"
"    if (!state) throw new TypeError('Illegal invocation: expected a text stream');\n"
"    return state;\n"
"  }\n"
"  function TextEncoderStream() {\n"
"    if (!new.target) throw new TypeError(\"TextEncoderStream requires 'new'\");\n"
"    const encoder = new Encoder();\n"
"    let pending = '';\n"
"    const stream = new TransformStream({\n"
"      transform: function (chunk, controller) {\n"
/* Encoding's DOMString conversion is ToString (hint string), not concatenation
 * (hint default). String(Symbol) is the exceptional constructor shortcut, so
 * reject symbols explicitly before calling the captured String intrinsic. */
"        if (typeof chunk === 'symbol') throw new TypeError('Cannot convert a Symbol to a string');\n"
"        let text = pending + StringType(chunk); pending = '';\n"
"        if (text.length) {\n"
"          const last = text.charCodeAt(text.length - 1);\n"
"          if (last >= 0xD800 && last <= 0xDBFF) { pending = text.slice(-1); text = text.slice(0, -1); }\n"
"        }\n"
"        if (text.length) controller.enqueue(encoder.encode(text));\n"
"      },\n"
"      flush: function (controller) { if (pending) controller.enqueue(encoder.encode('\\uFFFD')); }\n"
"    });\n"
"    encoders.set(this, stream);\n"
"    textBrands.add(this);\n"
"  }\n"
"  accessor(TextEncoderStream.prototype, 'encoding', function () { textOf(encoders, this); return 'utf-8'; });\n"
"  accessor(TextEncoderStream.prototype, 'readable', function () { return textOf(encoders, this).readable; });\n"
"  accessor(TextEncoderStream.prototype, 'writable', function () { return textOf(encoders, this).writable; });\n"
"  function TextDecoderStream(label, options) {\n"
"    if (!new.target) throw new TypeError(\"TextDecoderStream requires 'new'\");\n"
"    const decoder = new Decoder(label, options);\n"
"    const stream = new TransformStream({\n"
"      transform: function (chunk, controller) {\n"
"        const text = decoder.decode(chunk, { stream: true });\n"
"        if (text.length) controller.enqueue(text);\n"
"      },\n"
"      flush: function (controller) {\n"
"        const text = decoder.decode(); if (text.length) controller.enqueue(text);\n"
"      }\n"
"    });\n"
"    decoders.set(this, { decoder: decoder, stream: stream });\n"
"    textBrands.add(this);\n"
"  }\n"
"  for (const name of ['encoding', 'fatal', 'ignoreBOM'])\n"
"    accessor(TextDecoderStream.prototype, name, function () { return textOf(decoders, this).decoder[name]; });\n"
"  accessor(TextDecoderStream.prototype, 'readable', function () { return textOf(decoders, this).stream.readable; });\n"
"  accessor(TextDecoderStream.prototype, 'writable', function () { return textOf(decoders, this).stream.writable; });\n"
"  shared.publish('TextEncoderStream', TextEncoderStream, 0);\n"
"  shared.publish('TextDecoderStream', TextDecoderStream, 0);\n"
"}\n"
"return { installText: installText, is: function (value) { return states.has(value) || controllers.has(value) || textBrands.has(value); } };\n"
"})\n";

JSValue js_transform_install(JSContext *ctx, JSValueConst shared, JSValueConst readable, JSValueConst writable)
{
    JSValue fn = JS_Eval(ctx, SOURCE, sizeof SOURCE - 1, "<streams-transform>", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(fn)) return fn;
    JSValueConst args[3] = { shared, readable, writable };
    JSValue result = JS_Call(ctx, fn, JS_UNDEFINED, 3, args);
    JS_FreeValue(ctx, fn);
    return result;
}
