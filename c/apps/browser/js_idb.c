/* c/apps/browser/js_idb.c -- IndexedDB: a coherent, session-scoped subset.
 *
 * js_platform.h used to argue, correctly, that indexedDB should stay absent
 * until the bar below could be met: "every IDBRequest this build can
 * produce, on every path including the ones left unimplemented, terminates
 * in success or a thrown/fired error -- never silently pending." This file
 * is the implementation that meets it, and the structural argument for WHY
 * it meets it is worth stating before the code, because the code is long.
 *
 * THE ONE INVARIANT EVERYTHING ELSE IS BUILT AROUND: scheduleSettle() (below)
 * is the ONLY way an IDBRequest is ever produced. It (1) creates the request
 * object, (2) schedules its settle-task on G.setTimeout -- the SAME timer
 * queue js_page.c's g_timers already is, which js_page_pending() already
 * reports -- BEFORE running any implementation code, with a DEFAULT PAYLOAD
 * that is an error (an UnknownError DOMException), and only THEN (3) runs
 * the operation and overwrites the payload if it completes normally. A
 * request therefore cannot leave this file without a settle-task already on
 * the queue; there is no method here that returns an IDBRequest without
 * going through it. If a future edit adds a code path that forgets to
 * compute a result, the default payload fires error instead of hanging.
 *
 * A request created inside an aborting/aborted transaction is forced to the
 * error path (AbortError) at fire time regardless of what its own operation
 * computed (fireSettle checks txn._finished first) -- so "the transaction
 * aborted between this request creation and its settle-task running" is not
 * a third state, it collapses into the same error path.
 *
 * WHAT IS DELIBERATELY NOT HERE, refused rather than half-built (see
 * js_platform.h and the workflow scope note for the corpus counts):
 *   - Durability across a page load / reboot. In-memory only, scoped to one
 *     JSContext -- the SAME durability localStorage already has on this
 *     machine (js_webapi.c g_stores is a bare array with no file backing).
 *     There is no VFS positional write to build real durability on (CLAUDE.md
 *     structural gap #3), and a store that survives sometimes is worse than
 *     one that honestly does not, so this does not pretend to.
 *   - Blob/File as a stored value: put()/add() with one THROWS DataCloneError
 *     SYNCHRONOUSLY, at the call, the same shape as c/apps/libc ENOSYS rule
 *     -- refuse by name rather than hand back a request that resolves to
 *     something silently wrong.
 *   - IDBIndex.getAllRecords / IDBObjectStore.getAllRecords. Left undefined;
 *     feature detection reports false, correctly.
 *   - Worker / iframe scope. THIS SENTENCE USED TO READ "there are no workers
 *     and no nested browsing contexts in this tree", and it went stale the
 *     same day it was written: c/apps/browser/js_worker.c landed on
 *     2026-08-28 and builds a SECOND JSRuntime/JSContext with its own global
 *     (worker_install_globals), which this file is never invited to install
 *     into. The CONCLUSION is unchanged and still deliberate -- inside a
 *     Worker, `typeof indexedDB === 'undefined'`, which is the correct
 *     feature-detect answer for a scope where it genuinely is not there --
 *     but the reason is now a choice rather than an absence, so it has to be
 *     stated as one. Two things follow, and the next person to widen this
 *     should know both: (1) values do not cross JSRuntimes, so a shared
 *     store would need the structuredClone boundary at every call, not a
 *     pointer; (2) IndexedDB's whole point in a Worker is that the two scopes
 *     see the SAME database, and a per-worker store that silently did not
 *     would be present-and-wrong -- the exact failure this file exists to
 *     avoid. Absent is the right answer until that is built properly.
 *
 * SCOPE CHOICES WORTH NAMING, each a documented simplification rather than a
 * silent deviation:
 *   - The actual data operation for every request runs SYNCHRONOUSLY at call
 *     time (single JS thread, nothing else can mutate the store between the
 *     call and the deferred event); only the firing of success/error is
 *     deferred. This also makes cross-request ordering trivially correct:
 *     js_page.c timer loop fires same-tick, zero-delay timers in creation
 *     order (ascending seq), so requests settle in the order they were
 *     made, which is what most of the corpus assumes.
 *   - A transaction auto-commits via a task that reschedules itself while
 *     requests are still outstanding (txn._reqCount > 0) and commits once it
 *     reaches zero -- an idle transaction commits rather than lingering,
 *     without needing to model the spec synchronous-task activity window
 *     precisely. The cost, stated rather than hidden: TransactionInactiveError
 *     is enforced only once a transaction has actually finished, not for the
 *     spec narrower between-tasks window -- this build is MORE permissive
 *     than spec there, never silently less (a request that would have to
 *     throw synchronously in a real browser instead gets accepted and still
 *     terminates correctly here).
 *   - Event propagation does not implement generic DOM bubbling (the
 *     constructible EventTarget this stands on has none -- see js_events.c).
 *     request -> transaction -> connection propagation for unhandled errors
 *     is done as distinct, freshly-built events at each level rather than one
 *     event re-dispatched with a walked target, which is observationally the
 *     same for a non-composed leaf target and is what this corpus needs.
 *   - Cursors recompute their full candidate list from the store/index on
 *     every openCursor/continue/advance call rather than maintaining a live
 *     iterator. O(records) per step, correct by construction (no stale
 *     iterator state to get wrong), and fine at this scale -- the corpus
 *     stores hold tens of records, not millions.
 *
 * Install AFTER js_events_install (needs the real, constructible
 * EventTarget) and after js_platform_install (needs G.DOMException and
 * G.structuredClone). See js_idb.h.
 */

