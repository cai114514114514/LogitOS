#ifdef JS_IDB_NEGCTL
/* THE CONTROL FOR THE TERMINATION BAR ITSELF, not for any one method. It
 * replaces IDBObjectStore.prototype.get with exactly the shape
 * js_platform.h's old comment warned about: a REAL IDBRequest -- same
 * prototype, `instanceof IDBRequest` is true, readyState starts 'pending' --
 * that is simply never handed a settle-task. Nothing else in this file
 * changes. tests/idb.mk's test-idb-negctl build links this in and the host
 * gate's own quiescence check (every request must reach readyState==='done'
 * within a bounded pump) must go RED on exactly the one request this breaks
 * and pass on everything else -- see tests/unit/webapi_idb_test.c. */
static const char *IDB_NEGCTL_JS =
"(function (G) {\n"
"  if (!G.IDBObjectStore || !G.IDBRequest) return;\n"
"  G.IDBObjectStore.prototype.get = function (query) {\n"
"    if (arguments.length < 1) throw new TypeError('get requires 1 argument');\n"
"    var req = Object.create(G.IDBRequest.prototype);\n"
"    req.readyState = 'pending'; req.result = undefined; req.error = null;\n"
"    req.source = this; req.transaction = this.transaction;\n"
/*  Deliberately no G.setTimeout call here -- this is the bug, not a fixture
 *  bug. Everything else in this file still schedules-before-running. */
"    return req;\n"
"  };\n"
"})(typeof globalThis !== 'undefined' ? globalThis : this);\n";
#endif

void js_idb_install(JSContext *ctx)
{
    if (!ctx) return;
    JSValue r = JS_Eval(ctx, IDB_JS, strlen(IDB_JS), "<js_idb>", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(r)) {
        /* Loud, not silent -- the same rule js_events.c states: a prelude
         * that fails to install must not leave the page thinking it has no
         * indexedDB for an innocent reason. */
        JSValue e = JS_GetException(ctx);
        const char *s = JS_ToCString(ctx, e);
        fprintf(stderr, "js_idb: install failed: %s\n", s ? s : "(unprintable)");
        if (s) JS_FreeCString(ctx, s);
        JSValue st = JS_GetPropertyStr(ctx, e, "stack");
        if (!JS_IsUndefined(st)) {
            const char *ss = JS_ToCString(ctx, st);
            if (ss) { fprintf(stderr, "%s\n", ss); JS_FreeCString(ctx, ss); }
        }
        JS_FreeValue(ctx, st);
        JS_FreeValue(ctx, e);
    }
    JS_FreeValue(ctx, r);

#ifdef JS_IDB_NEGCTL
    {
        /* LOUD on failure to install, for the reason js_events.c gives for
         * the identical pattern: a control whose stub does not install is
         * byte-for-byte the real build, and it would then report the suite
         * it controls as meaningless-but-green -- the one verdict that is
         * not true. Abort rather than report a fiction. */
        JSValue n = JS_Eval(ctx, IDB_NEGCTL_JS, strlen(IDB_NEGCTL_JS),
                            "<js_idb_negctl>", JS_EVAL_TYPE_GLOBAL);
        if (JS_IsException(n)) {
            JSValue e = JS_GetException(ctx);
            const char *m = JS_ToCString(ctx, e);
            fprintf(stderr, "js_idb NEGCTL: stub did not install: %s\n", m ? m : "(unprintable)");
            fprintf(stderr, "js_idb NEGCTL: this build is identical to the real one -- its verdict is meaningless\n");
            if (m) JS_FreeCString(ctx, m);
            JS_FreeValue(ctx, e);
            exit(2);
        }
        JS_FreeValue(ctx, n);
    }
#endif
}
