/* js_cssom.c -- the CSSOM: CSSOM-View geometry, document.styleSheets, the CSS
 * namespace object, matchMedia, and the FontFaceSet stub.
 *
 * WHY THIS FILE EXISTS, in the form of a measurement rather than a wish. A WPT
 * run over the vendored corpus reports 1,926 files under css/ that never
 * completed the harness -- 88% of every harness death in the whole corpus, and
 * 28% of every CSS test file we have. A file that dies reports nothing, so
 * every subtest inside it is invisible and the CSS denominator is a fiction.
 *
 * Reading WHY a sample of them died, rather than assuming, produced a ranked
 * table (in build/cssom/, regenerated by `make wpt-cssom-rank`). The
 * assumption going in was that they die inside the CSSOM -- getComputedStyle,
 * cssRules, setProperty. That assumption was mostly WRONG, and the table is
 * the useful part of this work whether or not the code is. The two entries
 * this file is aimed at:
 *
 *   1049  the harness completed with ZERO subtests
 *          -- of which ~765 are `<body onload="checkLayout('.target')">`.
 *             The load event fires on the WINDOW; `<body onload>` is a WINDOW
 *             handler, not a body one; nothing here reflected it. So
 *             checkLayout was never called, no test() was ever registered,
 *             and the file timed out empty. Once it IS called it immediately
 *             needs offsetWidth, offsetTop, clientWidth, scrollWidth and
 *             getBoundingClientRect -- and of those, only the last existed.
 *     57  `CSS is not defined` -- no CSS namespace object at all, so a
 *          feature detect (`CSS.supports(...)`) threw on line one.
 *     10  `cannot read property 'cssRules' of undefined` -- document.styleSheets.
 *
 * (The ranking at the time also had 165 files on `document.fonts.ready`. The
 * web-API line fixed that one concurrently; see the note on SHIM_FONTS. It is
 * not in this file's numbers.)
 *
 * WHAT IS HONEST ABOUT THE GEOMETRY, said before the code and not after.
 * layout.c produces a FLAT display list, not a box tree. An element's border
 * box is recovered from it two ways: EXACTLY, when layout emitted the
 * element's own IT_RECT (any background or border does that), and otherwise as
 * the union of the boxes its subtree painted -- which is the INK extent, so a
 * background-less <div> reports the width of its widest line rather than its
 * containing block's width. That is the same compromise js_dom.c's
 * getBoundingClientRect already documents, for the same reason: making layout
 * emit an invisible rect per element would cost a display-list entry for every
 * node on every page to serve a call most pages never make. It is recorded
 * here as a KNOWN WRONG ANSWER for a class of elements, not as a rounding
 * error.
 *
 * And the numbers are only as good as the last layout. A real browser flushes
 * a pending reflow on any of these reads; so does this (see flush_layout) --
 * but only when layout.c is linked. The host WPT runner links neither layout.c
 * nor a font backend, so there every box is 0x0 and the revived check-layout
 * files complete and then FAIL. That is strictly better than dying, because a
 * failing subtest is IN the denominator and a dead file is not. It is not the
 * same as passing. Do not read a revived file as a fixed one.
 */

