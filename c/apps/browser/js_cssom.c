static int g_installed;

/* Evaluate one shim and SAY SO if it throws.
 *
 * This used to swallow the exception. A shim that fails to install does not
 * fail loudly -- the properties it was going to define simply are not there,
 * and every symptom shows up somewhere else entirely: window.onload reads
 * null, a body handler never runs, and the obvious suspect is the handler
 * logic rather than a SyntaxError on line 40 of a C string literal. That cost
 * a debugging session, so the swallow is gone. */
static void run_shim(JSContext *ctx, const char *src, const char *name)
{
    JSValue r = JS_Eval(ctx, src, strlen(src), name, JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(r)) {
        JSValue e = JS_GetException(ctx);
        const char *m = JS_ToCString(ctx, e);
        printf("[cssom] %s failed to install: %s\n", name, m ? m : "?");
        if (m) JS_FreeCString(ctx, m);
        JS_FreeValue(ctx, e);
    }
    JS_FreeValue(ctx, r);
}

static void def_getset(JSContext *ctx, JSValueConst proto, const char *name,
                       JSValue (*get)(JSContext *, JSValueConst, int),
                       JSValue (*set)(JSContext *, JSValueConst, JSValueConst, int),
                       int magic)
{
    JSAtom a = JS_NewAtom(ctx, name);
    JSValue g = JS_NewCFunction2(ctx, (JSCFunction *)get, name, 0,
                                 JS_CFUNC_getter_magic, magic);
    JSValue s = set ? JS_NewCFunction2(ctx, (JSCFunction *)set, name, 1,
                                       JS_CFUNC_setter_magic, magic)
                    : JS_UNDEFINED;
    JS_DefinePropertyGetSet(ctx, proto, a, g, s, JS_PROP_CONFIGURABLE);
    JS_FreeAtom(ctx, a);
}

void js_cssom_install(JSContext *ctx)
{
    if (!ctx) return;
    g_installed = 1;
    g_cache_node = 0; g_cache_ptr = 0;
    g_scrolln = 0;
    g_win_sx = g_win_sy = 0;
    g_saw_dirty = 0;
    g_sheetlist = JS_UNDEFINED;
    free(g_sheetsrc); g_sheetsrc = 0; g_sheetsrclen = 0;

    JSValue g = JS_GetGlobalObject(ctx);

    /* The Element prototype. `Element` is the one js_dom.c publishes when its
     * interface hierarchy is built; the createElement fallback is for a build
     * with JSDOM_NO_INTERFACE_HIERARCHY, which is exactly what the WPT
     * negative control uses -- so without the fallback the negative control
     * would fail for the wrong reason. */
    static const char *GETPROTO =
        "(typeof Element !== 'undefined' && Element.prototype) ||"
        " Object.getPrototypeOf(document.createElement('div'))";
    JSValue proto = JS_Eval(ctx, GETPROTO, strlen(GETPROTO), "<cssom>", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(proto)) { JS_FreeValue(ctx, JS_GetException(ctx)); proto = JS_NULL; }

    if (JS_IsObject(proto)) {
        def_getset(ctx, proto, "offsetWidth",  el_geom, 0, G_OFFSET_W);
        def_getset(ctx, proto, "offsetHeight", el_geom, 0, G_OFFSET_H);
        def_getset(ctx, proto, "offsetLeft",   el_geom, 0, G_OFFSET_L);
        def_getset(ctx, proto, "offsetTop",    el_geom, 0, G_OFFSET_T);
        def_getset(ctx, proto, "clientWidth",  el_geom, 0, G_CLIENT_W);
        def_getset(ctx, proto, "clientHeight", el_geom, 0, G_CLIENT_H);
        def_getset(ctx, proto, "clientLeft",   el_geom, 0, G_CLIENT_L);
        def_getset(ctx, proto, "clientTop",    el_geom, 0, G_CLIENT_T);
        def_getset(ctx, proto, "scrollWidth",  el_geom, 0, G_SCROLL_W);
        def_getset(ctx, proto, "scrollHeight", el_geom, 0, G_SCROLL_H);
        def_getset(ctx, proto, "scrollTop",  el_scroll_get, el_scroll_set, 0);
        def_getset(ctx, proto, "scrollLeft", el_scroll_get, el_scroll_set, 1);
        JS_SetPropertyStr(ctx, proto, "__cssomOffsetParentHops",
            JS_NewCFunction(ctx, el_offsetParentHops, "__cssomOffsetParentHops", 1));
        {
            /* Defined in JS so the walk goes through js_dom.c's wrapper cache
             * -- see the comment on el_offsetParentHops. */
            static const char *OP =
                "Object.defineProperty(("
                "  (typeof Element !== 'undefined' && Element.prototype) ||"
                "  Object.getPrototypeOf(document.createElement('div'))),"
                " 'offsetParent', { configurable: true, get: function () {"
                "   var n = this.__cssomOffsetParentHops(this);"
                "   if (n < 0) return null;"
                "   var p = this;"
                "   while (n-- > 0 && p) p = p.parentNode;"
                "   return p || null;"
                " } });";
            JSValue v = JS_Eval(ctx, OP, strlen(OP), "<cssom offsetParent>",
                                JS_EVAL_TYPE_GLOBAL);
            if (JS_IsException(v)) JS_FreeValue(ctx, JS_GetException(ctx));
            JS_FreeValue(ctx, v);
        }
        /* REPLACES js_dom.c's getBoundingClientRect. Same display list, two
         * differences that matter: this one flushes a pending layout first,
         * and it prefers the element's OWN painted rect over the subtree ink
         * union when layout emitted one. */
        JS_SetPropertyStr(ctx, proto, "getBoundingClientRect",
            JS_NewCFunction(ctx, el_getBoundingClientRect, "getBoundingClientRect", 0));
        JS_SetPropertyStr(ctx, proto, "getClientRects",
            JS_NewCFunction(ctx, el_getClientRects, "getClientRects", 0));

        /* The scrolling methods. `scroll` and `scrollTo` are the same
         * operation under two names, which is the spec's own wording. */
        JS_SetPropertyStr(ctx, proto, "scrollTo",
            JS_NewCFunction2(ctx, (JSCFunction *)el_scroll_meth, "scrollTo", 2,
                             JS_CFUNC_generic_magic, 0));
        JS_SetPropertyStr(ctx, proto, "scroll",
            JS_NewCFunction2(ctx, (JSCFunction *)el_scroll_meth, "scroll", 2,
                             JS_CFUNC_generic_magic, 0));
        JS_SetPropertyStr(ctx, proto, "scrollBy",
            JS_NewCFunction2(ctx, (JSCFunction *)el_scroll_meth, "scrollBy", 2,
                             JS_CFUNC_generic_magic, 1));
        JS_SetPropertyStr(ctx, proto, "scrollIntoView",
            JS_NewCFunction(ctx, el_scrollIntoView, "scrollIntoView", 1));
    }
    JS_FreeValue(ctx, proto);

    /* The CSS namespace object. */
    JSValue css = JS_NewObject(ctx);
    JS_SetPropertyStr(ctx, css, "supports", JS_NewCFunction(ctx, js_CSS_supports, "supports", 2));
    JS_SetPropertyStr(ctx, css, "escape",   JS_NewCFunction(ctx, js_CSS_escape, "escape", 1));
    JS_SetPropertyStr(ctx, g, "CSS", css);

    /* THE VIEWPORT HAS TO BE ONE NUMBER, for the same reason matchMedia below
     * has to be the cascade's own evaluator. js_webapi.c publishes
     * innerWidth/innerHeight from a viewport IT is told about, and the
     * cascade reads css_media_width()/css_media_height(); nothing keeps the
     * two in step, and in the host WPT runner they are 1180x572 and 800x600
     * respectively. That is not a cosmetic disagreement: a page computes
     * `4000 - window.innerWidth + el.clientWidth`, scrolls, and compares
     * against window.scrollX -- so the number it predicts with and the number
     * the scroller clamps with must be the same one, or every such assertion
     * is off by the difference (css/cssom-view/scrollintoview.html is 40
     * subtests of exactly that shape). The cascade's is authoritative because
     * it is the width layout was run at. */
    {
        int vw = view_w(), vh = view_h();
        JS_SetPropertyStr(ctx, g, "innerWidth",  JS_NewInt32(ctx, vw));
        JS_SetPropertyStr(ctx, g, "innerHeight", JS_NewInt32(ctx, vh));
        JS_SetPropertyStr(ctx, g, "outerWidth",  JS_NewInt32(ctx, vw));
        JS_SetPropertyStr(ctx, g, "outerHeight", JS_NewInt32(ctx, vh));
    }

    /* The window as a scrolling box. scrollX/pageXOffset are two names for
     * one value, and a page uses whichever its era taught it. */
    JS_SetPropertyStr(ctx, g, "scrollTo",
        JS_NewCFunction2(ctx, (JSCFunction *)win_scroll_meth, "scrollTo", 2,
                         JS_CFUNC_generic_magic, 0));
    JS_SetPropertyStr(ctx, g, "scroll",
        JS_NewCFunction2(ctx, (JSCFunction *)win_scroll_meth, "scroll", 2,
                         JS_CFUNC_generic_magic, 0));
    JS_SetPropertyStr(ctx, g, "scrollBy",
        JS_NewCFunction2(ctx, (JSCFunction *)win_scroll_meth, "scrollBy", 2,
                         JS_CFUNC_generic_magic, 1));
    def_getset(ctx, g, "scrollX",      win_scroll_get, 0, 1);
    def_getset(ctx, g, "pageXOffset",  win_scroll_get, 0, 1);
    def_getset(ctx, g, "scrollY",      win_scroll_get, 0, 0);
    def_getset(ctx, g, "pageYOffset",  win_scroll_get, 0, 0);
    JS_SetPropertyStr(ctx, g, "__cssomHitPaths",
        JS_NewCFunction(ctx, js_hitPaths, "__cssomHitPaths", 3));

    JS_SetPropertyStr(ctx, g, "DOMRect",
        JS_NewCFunction2(ctx, js_DOMRect, "DOMRect", 4, JS_CFUNC_constructor, 0));
    JS_SetPropertyStr(ctx, g, "DOMRectReadOnly",
        JS_NewCFunction2(ctx, js_DOMRect, "DOMRectReadOnly", 4, JS_CFUNC_constructor, 0));

    /* Wins over js_webapi.c's: see the note above js_matchMedia. */
    JS_SetPropertyStr(ctx, g, "matchMedia",
        JS_NewCFunction(ctx, js_matchMedia, "matchMedia", 1));

    /* document.styleSheets */
    JSValue doc = JS_GetPropertyStr(ctx, g, "document");
    if (JS_IsObject(doc)) {
        JSAtom a = JS_NewAtom(ctx, "styleSheets");
        JS_DefinePropertyGetSet(ctx, doc, a,
            JS_NewCFunction2(ctx, (JSCFunction *)doc_styleSheets, "styleSheets", 0,
                             JS_CFUNC_getter, 0),
            JS_UNDEFINED, JS_PROP_CONFIGURABLE);
        JS_FreeAtom(ctx, a);
    }
    JS_FreeValue(ctx, doc);
    JS_FreeValue(ctx, g);

    /* Last, and after the Element prototype above: it takes js_dom.c's
     * CSSStyleDeclaration and both widens and re-answers it. */
    install_style_decl(ctx);

    run_shim(ctx, SHIM_FONTS, "<cssom fonts>");
    run_shim(ctx, SHIM_VIEW, "<cssom view>");
    run_shim(ctx, SHIM_BODY_HANDLERS, "<cssom body handlers>");
}

void js_cssom_close(JSContext *ctx)
{
    if (!g_installed) return;
    g_installed = 0;
    g_cache_node = 0; g_cache_ptr = 0;
    free(g_scroll); g_scroll = 0; g_scrolln = g_scrollcap = 0;
    free(g_sheets); g_sheets = 0; g_nsheets = 0;
    /* The cached StyleSheetList holds a live GC reference; JS_FreeRuntime
     * asserts on one that outlives the context, which is why this is a close
     * hook and not just a static that gets forgotten at exit. */
    if (ctx) JS_FreeValue(ctx, g_sheetlist);
    g_sheetlist = JS_UNDEFINED;
    free(g_sheetsrc); g_sheetsrc = 0; g_sheetsrclen = 0;
}
